def test_the_disclaimer_doc_holds_the_disclaimer_byte_for_byte():
    """A second, hand-typed copy of a compliance string is a copy that drifts.

    `docs/DISCLAIMER.md` is generated by `tools/make_disclaimer.py`, and this
    asserts the generation did not quietly mangle it - a stray markdown escape
    or a reflowed line would both make the file *look* right.
    """
    from rag.guardrails import DISCLAIMER

    text = (DOCS / "DISCLAIMER.md").read_text(encoding="utf-8")
    assert DISCLAIMER in text, "docs/DISCLAIMER.md does not contain the exact string"
    assert text.count(DISCLAIMER) == 1, "the disclaimer appears more than once"


def test_the_disclaimer_is_the_prd_one():
    """PRD §11 fixes the wording. The code must not have quietly edited it."""
    from rag.guardrails import DISCLAIMER

    prd = (ROOT / "PRD.md").read_text(encoding="utf-8")
