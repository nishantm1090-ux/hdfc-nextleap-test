def test_the_readme_documents_a_retrieval_command_that_actually_exists():
    """Every `python -m X` in the README must be a real module with a __main__."""
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    mods = set(re.findall(r"python(?:\.exe)? -m ([\w.]+)", readme))
    # Not project modules: these are invoked through -m but are not part of
    # this codebase. `venv` comes from `python -m venv .venv` in the setup.
    external = {"pip", "pytest", "streamlit", "venv"}
    assert mods - external
    for mod in sorted(mods - external):
        path = ROOT / (mod.replace(".", "/") + ".py")
        assert path.exists(), f"README references {mod}, which does not exist"
        assert "__main__" in path.read_text(encoding="utf-8"), (
            f"README says `python -m {mod}` but it has no __main__ block")


def test_the_readme_never_says_the_demo_has_a_question_count_it_does_not():
    """`rag.retrieve --demo` and `rag.answer --demo` are different sets, and the
    README must not quote the wrong one."""
    import rag.answer as A
    import rag.retrieve as Rt

    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    n_answer = len(A.DEMO_QUESTIONS)
    m = re.search(r"rag\.retrieve --demo.{0,40}?(\d+) questions", readme, re.S)
    if m:
        src = (ROOT / "rag" / "retrieve.py").read_text(encoding="utf-8")
        n_retrieve = len(re.findall(r"^\s+\"[^\"]{10,}\",\s*$",
                                    src, re.M))
        assert int(m.group(1)) == n_retrieve, (
            f"README says the retrieve demo has {m.group(1)} questions")
    assert f"{n_answer}-question" in readme, (
        f"README should state the answer demo's real count ({n_answer})")
