"""Phase 9 delivery tests: the documents must describe this system, not a memory of it.

Documentation drift is invisible by construction. A number changes, the prose
does not, and the prose is what a reviewer reads and trusts. So the claims the
delivery documents make are asserted here, against the live pipeline and the
live data files.

This is deliberately not a spell-check or a link-checker. It checks the specific
numbers a reader would act on: the test count, the eval headline, the chunk
count, the number of sources, and whether the disclaimer in `docs/` is the same
bytes as the disclaimer the code returns.
"""

from __future__ import annotations

import csv
import json
import re
from pathlib import Path

import pytest

import common

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"

DELIVERABLES = [
    ROOT / "README.md",
    DOCS / "SOURCES.md",
    DOCS / "SOURCES.csv",
    DOCS / "SAMPLE_QA.md",
    DOCS / "DISCLAIMER.md",
    ROOT / "eval" / "report.md",
    ROOT / "PRD.md",
    DOCS / "architecture.md",
    DOCS / "implementation.md",
]


@pytest.mark.parametrize("path", DELIVERABLES, ids=lambda p: p.name)
def test_the_deliverable_exists_and_is_not_empty(path):
    assert path.exists(), f"{path.relative_to(ROOT)} is missing"
    assert path.stat().st_size > 400, f"{path.name} is suspiciously small"


