def test_every_source_link_in_sample_qa_is_a_real_corpus_url():
    urls = {c.get("source_url")
            for c in common.read_jsonl(common.path_for("chunks_file"))}
    text = (DOCS / "SAMPLE_QA.md").read_text(encoding="utf-8")
    for u in set(re.findall(r"Source: (https?://\S+)", text)):
        assert u in urls, f"{u} is cited but is not in the corpus"


def test_no_sample_qa_answer_shows_its_source_twice():
    """FR-8.4 is "the one source link".

    The stub appends a bare `Source: <url>` to `Answer.text` for the CLI, so a
    renderer that also prints the citation line shows it twice. This is the
    exact bug the UI hit; the doc would hit it the same way.
    """
    text = (DOCS / "SAMPLE_QA.md").read_text(encoding="utf-8")
    for block in re.findall(r"```\n(.*?)\n```", text, re.S):
        if "Source: http" in block:
            continue  # this is the citation block, which is allowed
        assert "Source: http" not in block, f"source rendered twice: {block[:90]!r}"


def test_every_refusal_in_sample_qa_carries_no_citation():
    """A refusal is a policy response, not a sourced fact."""
    text = (DOCS / "SAMPLE_QA.md").read_text(encoding="utf-8")
    for section in re.split(r"^### \d+\. ", text, flags=re.M)[1:]:
        head = section.split("```")[0]
        if "**`refusal" in head or "**`out_of_corpus" in head or "**`error" in head:
            assert "\nSource: http" not in section, (
                f"a refusal in SAMPLE_QA.md has a citation: {head[:70]!r}")


def test_no_sample_qa_answer_exceeds_three_sentences():
    from rag.guardrails import count_sentences

    text = (DOCS / "SAMPLE_QA.md").read_text(encoding="utf-8")
    checked = 0
    for block in re.findall(r"```\n(.*?)\n```", text, re.S):
        body = common.strip_inline_source(block).strip()
        if not body or body.startswith("Last updated"):
            continue
        n = count_sentences(body)
        assert n <= 3, f"{n} sentences: {body[:90]!r}"
        checked += 1
    assert checked >= 5, "no answer bodies found - the file may have changed shape"


