def test_sample_qa_has_between_five_and_ten_questions():
    """The brief asks for 5-10 sample Q&A. Ten covers all five schemes plus
    every refusal path without padding."""
    text = (DOCS / "SAMPLE_QA.md").read_text(encoding="utf-8")
    n = len(re.findall(r"^### \d+\. ", text, re.M))
