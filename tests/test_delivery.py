def test_the_readme_test_count_is_the_real_one():
    """'513 tests' in the README has to match `pytest -q`.

    Counting by collection rather than trusting the README is the only way this
    stays true; a doc test that reads the number out of the doc is worthless.
    """
    import subprocess
    import sys

    out = subprocess.run(
        [sys.executable, "-m", "pytest", "tests/", "-q", "--collect-only"],
        cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace",
    ).stdout
    m = re.search(r"(\d+) tests? collected", out)
    if not m:
        m = re.search(r"(\d+) / (\d+)", out)
    assert m, "could not count collected tests"
    total = int(m.group(1)) if m.lastindex and m.lastindex > 1 else int(m.group(1))
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    assert f"**{total} tests" in readme or f"{total} tests" in readme, (
        f"the README does not state the real test count ({total})")


